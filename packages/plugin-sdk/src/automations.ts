/**
 * @unm/plugin-sdk — automation template advertisement (capability 'updates' and
 * friends).
 *
 * A plugin may advertise ready-made automation rule drafts in /discover under
 * `automationTemplates`. The API persists them on the plugin row and serves
 * them through GET /automations/templates alongside its built-in templates.
 * The webapp's Automations page offers each template as a one-click starting
 * point: it opens the rule builder pre-filled with the draft, which the user
 * can edit before saving (nothing is created until they hit Save).
 *
 * Contract:
 *  - `id` is stable within the plugin (the API keys stored templates on
 *    (pluginId, templateId)); renaming a template in a new version keeps its
 *    identity.
 *  - `draft` is an AutomationDraft-shaped object (name/description/enabled/
 *    triggers[]/actions[]/cooldownSec) using the SAME block shapes as the API's
 *    automations module — trigger ids and action ids inside the draft are
 *    regenerated by the webapp when a rule is created from it, so templates may
 *    use any placeholder ids.
 */

/** One ready-made automation rule draft advertised by a plugin (or built in). */
export interface AutomationTemplate {
  /** Stable template identity within its source (plugin id or 'builtin'). */
  id: string;
  /** Display name for the catalog ("Auto-update apps without reboot"). */
  name: string;
  /** Short human description of what the rule does and when it fires. */
  description?: string;
  /** AutomationDraft-shaped pre-fill (triggers + actions blocks). */
  draft: Record<string, unknown>;
}
