/**
 * VPN-module actions for RouterOS (verified live on 7.21 LTS).
 *
 * WireGuard is the first-class tunnel on modern RouterOS and has full REST CRUD:
 *  - /interface/wireguard — one row per server; `PUT {name}` AUTO-GENERATES the
 *    X25519 key pair (verified live) and returns both keys in the response.
 *  - /interface/wireguard/peers — peers reference their server by `interface`
 *    name + carry public-key, allowed-address, endpoint, keepalive.
 *
 * IPsec is READ-ONLY here: site-to-site IPsec over REST needs a live second
 * peer to verify safely (peer/policy/proposal interplay), so the plugin exposes
 * an inventory read and leaves configuration to winbox/CLI or the SSH console.
 */

import { rosNumber, rosString } from '../routerosClient';
import type { ActionContext, ActionDescriptor } from './types';

type Row = Record<string, unknown>;

// --- wireguard.servers.read ---------------------------------------------------------------------------

export const wireguardServersReadAction: ActionDescriptor = {
  id: 'wireguard.servers.read',
  label: 'Read WireGuard servers',
  description: "Lists the router's WireGuard interfaces (/interface/wireguard) — name, listen port, MTU and PUBLIC key (the private key is never returned by UNM).",
  module: 'VPN',
  riskLevel: 'read',
  deviceCount: 1,
  inputSchema: {},
  execute: async (ctx) => {
    const rows = await ctx.client.get<Row[]>('/interface/wireguard').catch(() => [] as Row[]);
    return {
      success: true,
      details: {
        servers: rows.map((w) => ({
          name: rosString(w, ['name']) ?? null,
          listenPort: rosNumber(w, ['listen-port']),
          mtu: rosNumber(w, ['mtu']),
          publicKey: rosString(w, ['public-key']) ?? null,
          running: rosString(w, ['running']) === 'true',
          disabled: rosString(w, ['disabled']) === 'true',
        })),
      },
    };
  },
};

// --- wireguard.server.set -------------------------------------------------------------------------------

export const wireguardServerSetAction: ActionDescriptor = {
  id: 'wireguard.server.set',
  label: 'Create or update a WireGuard server',
  description: "Creates (or updates) a WireGuard interface. On CREATE the key pair is generated by RouterOS itself and returned in details — store it, UNM does not keep private keys. Idempotent by name.",
  module: 'VPN',
  riskLevel: 'write',
  deviceCount: 1,
  inputSchema: {
    name: { type: 'string', required: true, minLength: 1, maxLength: 64, description: "Interface name (e.g. wg0)" },
    listenPort: { type: 'number', min: 1, max: 65_535, description: "UDP listen port (default 51820; auto-assigned when omitted on create)" },
    mtu: { type: 'number', min: 68, max: 65_535, description: "MTU (default 1420)" },
    privateKey: { type: 'string', description: "Existing private key to import instead of generating a new one (update only — create always generates)" },
  },
  execute: async (ctx, input) => {
    const name = String(input.name ?? '').trim();

    const rows = await ctx.client.get<Row[]>('/interface/wireguard').catch(() => [] as Row[]);
    const existing = rows.find((w) => rosString(w, ['name']) === name);

    if (existing) {
      const body: Record<string, unknown> = {};
      if (typeof input.listenPort === 'number') body['listen-port'] = Math.floor(input.listenPort as number);
      if (typeof input.mtu === 'number') body['mtu'] = Math.floor(input.mtu as number);
      if (typeof input.privateKey === 'string' && input.privateKey.trim()) {
        // Re-keying — the peer set must be re-provisioned afterwards.
        body['private-key'] = input.privateKey.trim();
      }
      const id = rosString(existing, ['.id']);
      if (!id) return { success: false, error: `WireGuard ${name} has no .id — cannot update it.` };
      try {
        await ctx.client.patch(`/interface/wireguard/${id}`, body);
      } catch (e) {
        return { success: false, error: `Updating WireGuard server "${name}" failed: ${e instanceof Error ? e.message : String(e)}` };
      }
      const after = (await ctx.client.get<Row[]>('/interface/wireguard').catch(() => [] as Row[])).find((w) => rosString(w, ['name']) === name);
      if (!after) return { success: false, error: 'Verification failed — server vanished after update.' };
      const rekeyed = typeof input.privateKey === 'string' && !!input.privateKey.trim();
      return {
        success: true,
        applied: Object.keys(body).length > 0,
        details: {
          updated: name,
          publicKey: rosString(after, ['public-key']) ?? null,
          ...(rekeyed ? { warning: 'Private key replaced — all peers must be re-provisioned with the new public key.' } : {}),
        },
      };
    }

    // Create — RouterOS generates the key pair when no private-key is given.
    const body: Record<string, unknown> = { name };
    if (typeof input.listenPort === 'number') body['listen-port'] = Math.floor(input.listenPort as number);
    if (typeof input.mtu === 'number') body['mtu'] = Math.floor(input.mtu as number);
    let created: Row | null = null;
    try {
      const res = await ctx.client.put<Row>('/interface/wireguard', body);
      created = res && typeof res === 'object' ? res : null;
    } catch (e) {
      return { success: false, error: `Creating WireGuard server "${name}" failed: ${e instanceof Error ? e.message : String(e)}` };
    }

    const after = (await ctx.client.get<Row[]>('/interface/wireguard').catch(() => [] as Row[])).find((w) => rosString(w, ['name']) === name);
    if (!after) return { success: false, error: `Verification failed — WireGuard server "${name}" not present after create.` };
    return {
      success: true,
      applied: true,
      details: {
        created: name,
        // The generated keys come back in the PUT response (and on re-read).
        publicKey: rosString(after ?? created ?? {}, ['public-key']) ?? null,
        privateKey: rosString(created ?? {}, ['private-key']) ?? undefined,
        note: 'Store the returned private key — UNM does not persist it.',
      },
    };
  },
};

// --- wireguard.server.delete -------------------------------------------------------------------------------

export const wireguardServerDeleteAction: ActionDescriptor = {
  id: 'wireguard.server.delete',
  label: 'Delete a WireGuard server',
  description: "Removes a WireGuard interface by name (and its peers). Idempotent — an unknown name is a no-op.",
  module: 'VPN',
  riskLevel: 'write',
  deviceCount: 1,
  inputSchema: { name: { type: 'string', required: true, minLength: 1, maxLength: 64, description: "Interface name to remove" } },
  execute: async (ctx, input) => {
    const name = String(input.name ?? '').trim();
    const rows = await ctx.client.get<Row[]>('/interface/wireguard').catch(() => [] as Row[]);
    const target = rows.find((w) => rosString(w, ['name']) === name);
    if (!target) return { success: true, applied: false, details: { skipped: `no WireGuard server named "${name}"` } };

    // Peers referencing this interface go first.
    const peers = await ctx.client.get<Row[]>('/interface/wireguard/peers').catch(() => [] as Row[]);
    let removedPeers = 0;
    for (const p of peers) {
      if (rosString(p, ['interface']) !== name) continue;
      const id = rosString(p, ['.id']);
      if (!id) continue;
      await ctx.client.delete(`/interface/wireguard/peers/${id}`).catch(() => undefined);
      removedPeers += 1;
    }

    const id = rosString(target, ['.id']);
    if (!id) return { success: false, error: `WireGuard ${name} has no .id — cannot remove it.` };
    try {
      await ctx.client.delete(`/interface/wireguard/${id}`);
    } catch (e) {
      return { success: false, error: `Deleting WireGuard server "${name}" failed: ${e instanceof Error ? e.message : String(e)}` };
    }

    const after = (await ctx.client.get<Row[]>('/interface/wireguard').catch(() => [] as Row[])).find((w) => rosString(w, ['name']) === name);
    if (after) return { success: false, error: `Verification failed — WireGuard server "${name}" still present.` };
    return { success: true, applied: true, details: { deleted: name, removedPeers } };
  },
};

