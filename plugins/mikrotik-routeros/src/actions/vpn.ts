// --- wireguard.peer.add -------------------------------------------------------------------------------------

export const wireguardPeerAddAction: ActionDescriptor = {
  id: 'wireguard.peer.add',
  label: 'Add a WireGuard peer',
  description: "Adds a peer to an existing WireGuard server (/interface/wireguard/peers). Idempotent — an identical public-key on the same interface is left untouched.",
  module: 'VPN',
  riskLevel: 'write',
  deviceCount: 1,
  inputSchema: {
    interface: { type: 'string', required: true, minLength: 1, maxLength: 64, description: "WireGuard server name (from wireguard.servers.read)" },
    publicKey: { type: 'string', required: true, description: "Peer's X25519 public key" },
    allowedAddress: { type: 'string', required: true, description: "Allowed address(es) — CIDR(s), e.g. 10.42.0.2/32 or 10.42.0.0/24" },
    endpoint: { type: 'string', description: "Peer's public endpoint host[:port] (omit for inbound-only peers)" },
    persistentKeepalive: { type: 'string', maxLength: 16, description: "Persistent keepalive interval, e.g. 25s (default off)" },
  },
  execute: async (ctx, input) => {
    const iface = String(input.interface ?? '').trim();
    const publicKey = String(input.publicKey ?? '').trim();
    const allowedAddress = String(input.allowedAddress ?? '').trim();

    // The server must exist.
    const servers = await ctx.client.get<Row[]>('/interface/wireguard').catch(() => [] as Row[]);
    if (!servers.some((w) => rosString(w, ['name']) === iface)) {
      return { success: false, error: `No WireGuard server named "${iface}" — create it first with wireguard.server.set.` };
    }

    const peers = await ctx.client.get<Row[]>('/interface/wireguard/peers').catch(() => [] as Row[]);
    if (peers.some((p) => rosString(p, ['interface']) === iface && rosString(p, ['public-key']) === publicKey)) {
      return { success: true, applied: false, details: { skipped: `peer ${publicKey.slice(0, 8)}… already on ${iface}` } };
    }

    const body: Record<string, unknown> = { interface: iface, 'public-key': publicKey, 'allowed-address': allowedAddress };
    if (typeof input.endpoint === 'string' && input.endpoint.trim()) body['endpoint'] = input.endpoint.trim();
    if (typeof input.persistentKeepalive === 'string' && input.persistentKeepalive.trim()) body['persistent-keepalive'] = input.persistentKeepalive.trim();

    try {
      await ctx.client.put('/interface/wireguard/peers', body);
    } catch (e) {
      return { success: false, error: `Adding WireGuard peer failed: ${e instanceof Error ? e.message : String(e)}` };
    }

    const after = (await ctx.client.get<Row[]>('/interface/wireguard/peers').catch(() => [] as Row[])).find(
      (p) => rosString(p, ['interface']) === iface && rosString(p, ['public-key']) === publicKey
    );
    if (!after) return { success: false, error: 'Verification failed — peer not present after create.' };
    return { success: true, applied: true, details: { added: `${iface} ← ${publicKey.slice(0, 8)}… (${allowedAddress})` } };
  },
};

// --- wireguard.peer.delete ------------------------------------------------------------------------------------

export const wireguardPeerDeleteAction: ActionDescriptor = {
  id: 'wireguard.peer.delete',
  label: 'Remove a WireGuard peer',
  description: "Removes a peer by its public key on the given interface. Idempotent — an unknown peer is a no-op.",
  module: 'VPN',
  riskLevel: 'write',
  deviceCount: 1,
  inputSchema: {
    interface: { type: 'string', required: true, minLength: 1, maxLength: 64, description: "WireGuard server name" },
    publicKey: { type: 'string', required: true, description: "Peer's X25519 public key to remove" },
  },
  execute: async (ctx, input) => {
    const iface = String(input.interface ?? '').trim();
    const publicKey = String(input.publicKey ?? '').trim();

    const peers = await ctx.client.get<Row[]>('/interface/wireguard/peers').catch(() => [] as Row[]);
    const target = peers.find((p) => rosString(p, ['interface']) === iface && rosString(p, ['public-key']) === publicKey);
    if (!target) return { success: true, applied: false, details: { skipped: `no peer ${publicKey.slice(0, 8)}… on ${iface}` } };

    const id = rosString(target, ['.id']);
    if (!id) return { success: false, error: 'Peer has no .id — cannot remove it.' };
    try {
      await ctx.client.delete(`/interface/wireguard/peers/${id}`);
    } catch (e) {
      return { success: false, error: `Removing WireGuard peer failed: ${e instanceof Error ? e.message : String(e)}` };
    }

    const after = (await ctx.client.get<Row[]>('/interface/wireguard/peers').catch(() => [] as Row[])).find(
      (p) => rosString(p, ['interface']) === iface && rosString(p, ['public-key']) === publicKey
    );
    if (after) return { success: false, error: 'Verification failed — peer still present.' };
    return { success: true, applied: true, details: { removed: `${iface} ← ${publicKey.slice(0, 8)}…` } };
  },
};

// --- ipsec.read (inventory only) -------------------------------------------------------------------------------

export const ipsecReadAction: ActionDescriptor = {
  id: 'ipsec.read',
  label: 'Read IPsec configuration (inventory)',
  description: "Inventory of the router's IPsec setup — peers, proposals, policies and identities (/ip/ipsec/*). Read-only: site-to-site IPsec writes are not exposed over REST yet (needs a live second peer to verify); configure via winbox/CLI or the SSH console.",
  module: 'VPN',
  riskLevel: 'read',
  deviceCount: 1,
  inputSchema: {},
  execute: async (ctx) => {
    const [peers, proposals, policies, identities] = await Promise.all([
      ctx.client.get<Row[]>('/ip/ipsec/peer').catch(() => [] as Row[]),
      ctx.client.get<Row[]>('/ip/ipsec/proposal').catch(() => [] as Row[]),
      ctx.client.get<Row[]>('/ip/ipsec/policy').catch(() => [] as Row[]),
      ctx.client.get<Row[]>('/ip/ipsec/identity').catch(() => [] as Row[]),
    ]);
    return {
      success: true,
      details: {
        peers: peers.map((p) => ({ name: rosString(p, ['name']) ?? '', address: rosString(p, ['address']) ?? null, localIdentity: rosString(p, ['local-identity']) ?? '', remoteIdentity: rosString(p, ['remote-identity']) ?? '' })),
        proposals: proposals.map((p) => ({ name: rosString(p, ['name']) ?? '', encAlgorithms: rosString(p, ['enc-algorithms']) ?? null, authAlgorithms: rosString(p, ['auth-algorithms']) ?? null, lifetime: rosString(p, ['lifetime']) ?? null })),
        policies: policies.map((p) => ({ srcAddress: rosString(p, ['src-address']) ?? '', dstAddress: rosString(p, ['dst-address']) ?? '', protocol: rosString(p, ['protocol']) ?? '', action: rosString(p, ['action']) ?? '' })),
        identities: identities.map((i) => ({ kind: rosString(i, ['kind']) ?? null, address: rosString(i, ['address']) ?? '', fqdn: rosString(i, ['fqdn']) ?? '' })),
      },
    };
  },
};

